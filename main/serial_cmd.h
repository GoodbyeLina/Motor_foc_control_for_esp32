#ifndef SERIAL_CMD_H
#define SERIAL_CMD_H

/**
 * ======================================================
 *  串口命令系统 - 通过串口控制电机
 * ======================================================
 * 
 * 使用方法:
 *   打开串口监视器 (115200 baud)，输入命令后回车
 * 
 * 可用命令:
 *   ┌──────────┬─────────────────────────────────────┐
 *   │ 命令     │ 说明                                 │
 *   ├──────────┼─────────────────────────────────────┤
 *   │ help     │ 显示本帮助信息                       │
 *   │ v <num>  │ 设置目标速度 (rad/s)                 │
 *   │          │ 例: v 5     → 目标速度 5 rad/s       │
 *   │          │ 例: v -3    → 反向 3 rad/s           │
 *   ├──────────┼─────────────────────────────────────┤
 *   │ c <num>  │ 设置目标电流 (A)                     │
 *   │          │ 例: c 0.5   → 目标电流 0.5A          │
 *   │          │ 例: c 0     → 停止（电流环模式下）    │
 *   ├──────────┼─────────────────────────────────────┤
 *   │ s        │ 停止电机 (输出电压0)                 │
 *   ├──────────┼─────────────────────────────────────┤
 *   │ mode     │ 切换控制模式:                        │
 *   │          │   0 = 开环 (无需编码器)              │
 *   │          │   1 = 电流闭环                       │
 *   │          │   2 = 速度闭环 (默认)                │
 *   │          │ 例: mode 2  → 切换到速度闭环         │
 *   └──────────┴─────────────────────────────────────┘
 * 
 * 示例操作流程:
 *   1. 烧录后打开串口监视器
 *   2. 输入 "v 5" → 电机以 5 rad/s 运转
 *   3. 输入 "v 0" → 电机停止
 *   4. 输入 "help" → 随时查看帮助
 * ======================================================
 */

#include <stdint.h>

/** 控制模式枚举 */
typedef enum {
    CTRL_MODE_OPENLOOP = 0,   // 开环模式
    CTRL_MODE_CURRENT = 1,    // 电流闭环
    CTRL_MODE_VELOCITY = 2,   // 速度闭环 (默认)
    CTRL_MODE_SENSORLESS = 3,
} ctrl_mode_t;

/** 串口命令解析结果 */
typedef struct {
    int   parsed;             // 是否成功解析 (1=成功, 0=失败)
    float target_velocity;    // 目标速度 (rad/s)
    float target_current;     // 目标电流 (A)
    ctrl_mode_t control_mode;// 控制模式
    uint8_t stop;            // 停止标志
} serial_cmd_result_t;

/**
 * 初始化串口命令系统
 */
void serial_cmd_init(void);

/**
 * 处理串口输入
 * @param result  [out] 命令解析结果
 * @return  1=有新的命令, 0=无新命令
 */
uint8_t serial_cmd_process(serial_cmd_result_t *result);

/**
 * 打印帮助信息
 */
void serial_print_help(void);

#endif